import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const exec = promisify(execFile);
const root = fileURLToPath(new URL('../', import.meta.url));
const binary = process.env.MARKET_CLAUDE_BINARY || 'claude';
const config = JSON.parse(await readFile(path.join(root, 'market.config.json'), 'utf8'));
const verification = path.join(root, '.cache/verification');
await mkdir(verification, { recursive: true });
const profile = await mkdtemp(path.join(verification, 'claude-profile-'));
const environment = { ...process.env, CLAUDE_CONFIG_DIR: profile, CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: '1', DISABLE_AUTOUPDATER: '1' };
const run = async args => (await exec(binary, args, { cwd: root, env: environment, timeout: 120000, maxBuffer: 8 * 1024 * 1024 })).stdout.trim();
const version = await run(['--version']);
const validation = await run(['plugin', 'validate', root]);
await run(['plugin', 'marketplace', 'add', root]);
const listing = JSON.parse(await run(['plugin', 'list', '--available', '--json']));
const expected = JSON.parse(await readFile(path.join(root, '.claude-plugin/marketplace.json'), 'utf8')).plugins;
const catalog = JSON.parse(await readFile(path.join(root, 'catalog/catalog.json'), 'utf8'));
const available = listing.available.filter(plugin => plugin.marketplaceName === config.name);
assert.equal(available.length, expected.length, 'Claude must discover every applicable marketplace entry');
const installedSkillCounts = {};
const inventories = [];
for (const id of ['research-paper-writing', 'academic-toolkit', 'ai-research-skills', 'live-session-fetcher']) {
  await run(['plugin', 'install', id + '@' + config.name]);
  const details = await run(['plugin', 'details', id + '@' + config.name]);
  const pkg = catalog.packages.find(pkg => pkg.id === id);
  const skills = pkg.agentSkills['claude-code'] || pkg.skills;
  const count = Number(details.match(/Skills \((\d+)\)/)?.[1]);
  assert.equal(count, skills.length, id + ': every skill in the repository collection must load');
  for (const skill of skills) assert.ok(details.includes(skill.name), id + ': ' + skill.name);
  installedSkillCounts[id] = count;
  inventories.push(details);
}
const installed = JSON.parse(await run(['plugin', 'list', '--json']));
const plugins = Array.isArray(installed) ? installed : installed.installed;
for (const id of Object.keys(installedSkillCounts)) assert.ok(plugins.some(plugin => (plugin.id || plugin.pluginId) === id + '@' + config.name));
const report = { client: version, marketplaceValidation: validation, marketplaceEntriesDiscovered: available.length, nativePluginInstalled: true, componentInventoryLoaded: true, installedSkillCounts, modelRequests: 0 };
await writeFile(path.join(verification, 'claude-details.txt'), inventories.join('\n\n') + '\n');
await writeFile(path.join(verification, 'claude.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
